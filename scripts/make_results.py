"""Generate RESULTS.md and results/summary.json from
results/scores.json, under the frozen rules of PREREGISTRATION.md
Sections 5 and 6. Nothing is hand-typed.
"""

import json
import os
from collections import Counter, defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOTAL_ROWS = 30
SERVICES = ("s3", "sqs", "lambda")
# Rows rescored by scripts/rerun_rows.py before that script kept the
# replaced record and noted the rerun itself (DECISIONS.md D5, D7).
# PREREGISTRATION.md Section 5 asks that a rerun be noted on the row;
# for these four the note is added here, at render time, so the raw
# records stay as recorded. Value: the row's run-1 status.
EARLY_RERUNS = {"S3-09": "DIVERGES", "S3-12": "ERROR", "L-02": "ERROR", "L-03": "ERROR"}


def load_records():
    with open(os.path.join(REPO, "results", "scores.json")) as fh:
        return json.load(fh)


def verdicts(records):
    by_id = {r["id"]: r for r in records}
    statuses = Counter(r["status"] for r in records)
    errors = statuses.get("ERROR", 0)

    matches = statuses.get("MATCHES", 0)
    share = matches / TOTAL_ROWS if TOTAL_ROWS else 0.0
    if errors or len(records) != TOTAL_ROWS:
        h1 = "INCONCLUSIVE"
    else:
        h1 = "CONFIRMED" if share >= 0.70 else "REFUTED"

    per_service_bad = {}
    for svc in SERVICES:
        per_service_bad[svc] = any(
            r["status"] in ("DIVERGES", "UNSUPPORTED")
            for r in records
            if r["service"] == svc
        )
    if errors:
        h2 = "INCONCLUSIVE"
    else:
        h2 = "CONFIRMED" if all(per_service_bad.values()) else "REFUTED"

    q02 = by_id.get("Q-02", {}).get("status")
    q04 = by_id.get("Q-04", {}).get("status")
    if q02 in (None, "ERROR") or q04 in (None, "ERROR"):
        h3 = "INCONCLUSIVE"
    else:
        h3 = (
            "CONFIRMED"
            if q02 == "MATCHES" and q04 == "MATCHES"
            else "REFUTED"
        )

    return {
        "H1": h1,
        "H2": h2,
        "H3": h3,
        "matches": matches,
        "total_rows": len(records),
        "share_matches": round(share, 4),
        "status_counts": dict(statuses),
        "per_service_bad": per_service_bad,
        "q02_status": q02,
        "q04_status": q04,
    }


def per_service_counts(records):
    counts = defaultdict(Counter)
    for rec in records:
        counts[rec["service"]][rec["status"]] += 1
        counts[rec["service"]]["TOTAL"] += 1
    return {svc: dict(c) for svc, c in sorted(counts.items())}


def render(records, verdict):
    lines = []
    lines.append("# Results: boto3 AWS Emulation Lab")
    lines.append("")
    lines.append(
        "Generated by scripts/make_results.py from results/scores.json. "
        "Verdict rules: PREREGISTRATION.md Section 6. Behaviour "
        "expectations: BEHAVIOURS.md."
    )
    lines.append("")
    lines.append("## Verdicts")
    lines.append("")
    lines.append(
        "- H1 (at least 70 percent of the 30 frozen rows score "
        "MATCHES): **%s** (%d of %d rows, share %.1f percent)"
        % (
            verdict["H1"],
            verdict["matches"],
            verdict["total_rows"],
            100.0 * verdict["share_matches"],
        )
    )
    lines.append(
        "- H2 (each service has at least one DIVERGES or UNSUPPORTED "
        "row): **%s** (s3: %s, sqs: %s, lambda: %s)"
        % (
            verdict["H2"],
            verdict["per_service_bad"]["s3"],
            verdict["per_service_bad"]["sqs"],
            verdict["per_service_bad"]["lambda"],
        )
    )
    lines.append(
        "- H3 (Q-02 visibility timeout and Q-04 dead-letter redrive "
        "both MATCHES): **%s** (Q-02 %s, Q-04 %s)"
        % (verdict["H3"], verdict["q02_status"], verdict["q04_status"])
    )
    lines.append("")
    lines.append("## Counts")
    lines.append("")
    lines.append("| Scope | MATCHES | DIVERGES | UNSUPPORTED | ERROR | Total |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    counts = per_service_counts(records)
    for svc in ("s3", "sqs", "lambda"):
        c = counts.get(svc, {})
        lines.append(
            "| %s | %d | %d | %d | %d | %d |"
            % (
                svc,
                c.get("MATCHES", 0),
                c.get("DIVERGES", 0),
                c.get("UNSUPPORTED", 0),
                c.get("ERROR", 0),
                c.get("TOTAL", 0),
            )
        )
    total = Counter()
    for c in counts.values():
        total.update(c)
    lines.append(
        "| all | %d | %d | %d | %d | %d |"
        % (
            total.get("MATCHES", 0),
            total.get("DIVERGES", 0),
            total.get("UNSUPPORTED", 0),
            total.get("ERROR", 0),
            len(records),
        )
    )
    lines.append("")
    lines.append("## Scored rows")
    lines.append("")
    for rec in records:
        lines.append("### %s (%s): %s" % (rec["id"], rec["service"], rec["status"]))
        lines.append("")
        if rec.get("unsupported_text"):
            lines.append("Emulator refusal, quoted: `%s`" % rec["unsupported_text"])
            lines.append("")
        if rec.get("harness_error"):
            lines.append("Harness error: `%s`" % rec["harness_error"])
            lines.append("")
        for a in rec["assertions"]:
            mark = "ok" if a["ok"] else "FAILED"
            lines.append(
                "- [%s] %s: expected %s, observed %s"
                % (mark, a["name"], a["expected"], a["observed"])
            )
        for note in rec["notes"]:
            lines.append("- note: %s" % note)
        if rec["id"] in EARLY_RERUNS and not any(n.startswith("rerun:") for n in rec["notes"]):
            lines.append(
                "- rerun: rescored once by scripts/rerun_rows.py after scored run 1 "
                "(DECISIONS.md D5); run 1 scored this row %s; the run-1 record was "
                "overwritten and is not kept in the repository (DECISIONS.md D7)"
                % EARLY_RERUNS[rec["id"]]
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    records = load_records()
    verdict = verdicts(records)
    summary = {"verdicts": verdict, "per_service_counts": per_service_counts(records)}
    with open(os.path.join(REPO, "results", "summary.json"), "w") as fh:
        json.dump(summary, fh, indent=1, sort_keys=True)
    with open(os.path.join(REPO, "RESULTS.md"), "w") as fh:
        fh.write(render(records, verdict))
    print(json.dumps(verdict, indent=1))


if __name__ == "__main__":
    main()
